// Базовое освещение на весь путь камеры (небо -> облака -> земля).
// Раньше единственным источником света был тусклый ambientLight внутри
// SkyZone (intensity 0.15) — этого хватало у солнца, но у земли не было
// вообще ничего своего, поэтому нижняя часть сцены выглядела чёрной.
// Здесь — постоянный базовый уровень освещённости, зоны добавляют свои
// акцентные источники поверх него.
export function SceneLighting() {
  return (
    <>
      <hemisphereLight color="#8fb3ff" groundColor="#1b2a22" intensity={0.6} />
      <directionalLight color="#fff4e0" position={[30, 60, 20]} intensity={1.1} />
    </>
  )
}
