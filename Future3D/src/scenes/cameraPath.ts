//
// ВТОРАЯ итерация: значения пересчитаны под новое расписание (сближение
// с солнцем теперь на progress=0.156/jf33%, а не ~0.32/jf50%, см.
// remapPathProgress выше) - HOLD чуть позже самого сближения (jf40%),
// END - до начала спуска к Земле (jf50%, заметно раньше DESCENT_START
// на jf60%, чтобы взгляд успел вернуться "по курсу" ДО того, как
