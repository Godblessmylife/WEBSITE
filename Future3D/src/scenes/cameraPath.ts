export const SOLAR_SYSTEM_LOOKAT_END = 0.322

// Финальная точка пути (0, 1.6, 0) - рост человека. Но progress (store)
// физически НИКОГДА не достигает 1.0, пока 3D-сцена видна: sticky-
// обёртка отпускает сцену раньше (проверено расчётом — реальный
// максимум зависит от высоты вьюпорта и остального контента страницы,
// обычно ~0.85).
//
// ВТОРАЯ итерация переразметки. Раньше здесь стояла ОДНА точка перегиба
// (растягивала только самый хвост пути, чтобы долететь до земли, а не
// зависнуть в 10+ units над поверхностью). Клиент затем задал уже ТРИ
// независимых временных ориентира сразу для всего путешествия ("с 0%
// до 33% доходить до солнца — сейчас это ~53%; после 60% — спуск к
// Земле через стратосферу"), поэтому переразметка обобщена на ДВА
// перегиба вместо одного — по одному на каждый ориентир, — а не только
// на финальный нырок.
//
// Принципиально: сами 3D-точки пути (CAMERA_PATH_POINTS выше) НЕ
// трогаются - вся более ранняя работа над ними (безопасная дистанция
// пролёта мимо солнца, обход вырождения "право" камеры через x=3 на
// P5/P6) никак не связана с тем, КАК БЫСТРО progress движется вдоль
// уже готовой кривой. Меняется только сама функция переразметки:
// раньше она была тождественной (t=progress) до одного порога и
// растягивала только хвост; теперь это кусочно-линейная функция с
// двумя опорными точками, подобранными числовым расчётом (см. историю
// в scratchpad-скриптах этой сессии, тот же метод, что и везде в этом
// файле) так, чтобы:
//  - точка максимального сближения с солнцем (совпадает с P3, t=0.3252)
//    приходилась ровно на jf=33% (SUN_CLOSEST_T ниже);
//  - начало настоящего спуска к Земле (совпадает с P4, t=0.6115)
//    приходилось на jf=60% (DESCENT_START_T ниже);
//  - хвост после этого работает как и раньше — тянется к MAX_DIVE_T,
//    но не дальше реально достижимого максимума progress.
//
// JF_SCALE - тот же коэффициент "доля видимого путешествия от всей
// страницы", что JourneyTuner.tsx считает через DOM
// (journeyScrollRangePx()/totalRange). Захардкожен, а не измерен здесь
// заново: этот модуль не может трогать DOM (используется и вне
// браузера — числовым скриптом при подборе этих самых констант), а сама
// зависимость и так уже приблизительная — тот же характер допущения,
// что и у остальных fixed-progress порогов в этом файле/FogController/
// StratosphereFlash (все тоже "верно при текущей длине страницы").
const JF_SCALE = 0.758

function jfToProgress(jf: number): number {
  const x = THREE.MathUtils.clamp(jf * JF_SCALE, 0, 1)
  return x * x * (3 - 2 * x) // easeProgress, продублировано - см. scrollEasing.ts
}

const SUN_CLOSEST_T = 0.3252 // совпадает с P3
const DESCENT_START_T = 0.6115 // совпадает с P4

// По отзыву клиента: на самой нулевой точке (progress=0, страница ещё не
// прокручена) солнечная система была видна "слишком далеко" - camera
// стояла в P0=(0,60,0), самом начале кривой. Клиент сравнил варианты
// через тюнер путешествия (JourneyTuner.tsx) и выбрал вид на jf=23% как
// желаемую СТАРТОВУЮ точку. Вместо сдвига самих 3D-точек пути (что
// изменило бы форму кривой и весь последующий расчёт пролёта мимо
// солнца) - переразметка t для сегмента 0..BP1_PROGRESS начинается не с
// t=0, а с t, который раньше соответствовал jf=23% - тот же t=SUN_CLOSEST_T
// на BP1_PROGRESS (jf=33%) сохранён, чтобы не трогать уже откалиброванный
// момент максимального сближения с солнцем и всё, что от него зависит
// ниже (SOLAR_SYSTEM_LOOKAT_HOLD/END и т.д.).
const JOURNEY_START_JF = 0.23
// MAX_DIVE_T = 1.0 (буквально долететь до (0,1.6,0)) — проверено
// скриншотами — оказался ПЕРЕбором: на дистанции меньше ~5 units от
// поверхности 4096x2048 текстура Земли не даёт никакой дополнительной
// детализации (не хватает разрешения) и превращается в размытое
// однотонное пятно. 0.85 — компромисс, даёт дистанцию до поверхности
// ~6.4 units — заметно ближе, чем недостижимый максимум "как было"
// (~10.8), но всё ещё в зоне, где спутниковая текстура читается чётко
// (горы, побережья, облака, океан — проверено скриншотом).
const MAX_DIVE_T = 0.85

const BP1_PROGRESS = jfToProgress(0.33)
const BP2_PROGRESS = jfToProgress(0.6)
// t, который раньше (до сдвига стартовой точки) соответствовал jf=23% -
// та же линейная формула, что и в первой ветке remapPathProgress ниже,
// просто вычисленная один раз на модульном уровне для JOURNEY_START_JF.
const JOURNEY_START_T = (jfToProgress(JOURNEY_START_JF) / BP1_PROGRESS) * SUN_CLOSEST_T

export function remapPathProgress(progress: number, maxReachableProgress: number): number {
  if (progress <= BP1_PROGRESS) {
    const localT = progress / BP1_PROGRESS
    return JOURNEY_START_T + localT * (SUN_CLOSEST_T - JOURNEY_START_T)
  }
  if (progress <= BP2_PROGRESS) {
    const localT = (progress - BP1_PROGRESS) / (BP2_PROGRESS - BP1_PROGRESS)
    return SUN_CLOSEST_T + localT * (DESCENT_START_T - SUN_CLOSEST_T)
  }
  const localT = THREE.MathUtils.clamp(
    (progress - BP2_PROGRESS) / (maxReachableProgress - BP2_PROGRESS),
    0,
    1,
  )
  return DESCENT_START_T + localT * (MAX_DIVE_T - DESCENT_START_T)
}

