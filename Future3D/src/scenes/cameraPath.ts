import * as THREE from 'three'

// Путь камеры сверху вниз: глубокое небо -> подлёт к солнечной системе ->
// атмосфера -> облака -> зона портфолио (почти горизонтальный участок) ->
// подход к земле -> город.
//
// БЫЛО одной точкой (0,52,33) для всего подлёта к солнцу — держало
// ближайшее сближение ~7 units (угловой размер солнца физически не
// помещался в кадр, "хлопок" при пролёте) либо, после первой правки,
// ~27 units (пролёт стал мягче, но клиент увидел это как "приближение
// стало слабее, чем было"). Проблема была не в САМОЙ близости, а в том,
// что путь проходил её ЗА СЧИТАНЫЕ ПРОЦЕНТЫ скролла — одна точка не может
// одновременно и держать сближение долго, и не давать резкого хлопка.
//
// Теперь подлёт к солнцу — это ТРИ точки (P1-P3), растянутые на широкое
// окно 20-55% видимого путешествия (проверено расчётом по формуле
// progress = easeProgress(jf * scaleFactor) — см. JourneyTuner.tsx):
// 0-20% (P0->P1) — дистанция до цели уже заметно падает (было ~4 units
// за это окно, стало ~7) при том что высота почти не меняется (клиент:
// "не опускать так низко под солнечную систему" про соседнее окно);
// 20-40% (P1->P2) — дистанция продолжает падать, высота остаётся ВЫШЕ
// высоты самой солнечной системы (Y target = 50) всё это время;
// 40-55% (P2->P3->начало P4) — минимальное расстояние ~7 units
// (тот же безопасный минимум, что и в самой первой версии - "с запасом,
// чтобы не влететь внутрь меша"), но растянутое по широкой дуге, а не
// точка - угловой размер солнца нарастает и спадает плавно на протяжении
// добрых 15% скролла, а не хлопает за один кадр.
// Y на P1-P3 держится заметно ВЫШЕ высоты самой солнечной системы
// (SOLAR_SYSTEM_TARGET.y = 50) - даже в точке максимального сближения
// (P3) камера на ~4-5 units выше диска, а не на его уровне. Причина не
// эстетическая, а геометрическая: орбиты в solar_system.glb - это
// плоские тонкие кольца (проверено: gltf-transform inspect показывает
// один и тот же меш-примитив с 9 инстансами - по одному кольцу на
// планету). Если камера оказывается В ПЛОСКОСТИ этих колец (Y ≈ 50),
// они вырождаются в путаницу длинных прямых линий, пересекающих кадр
// в произвольных направлениях (именно это клиент увидел как "резкие
// лучи в хаотичном направлении" - раньше камера пролетала эту зону
// слишком быстро, чтобы это бросалось в глаза, а после растягивания
// сближения на широкое окно 20-55% стало заметно). Оставаясь выше
// плоскости, кольца всегда видны под углом и читаются как эллипсы, а
// не как каша из линий.
export const CAMERA_PATH_POINTS = [
  new THREE.Vector3(0, 60, 0),
  new THREE.Vector3(0, 58, 15),
  new THREE.Vector3(0, 56, 27),
  new THREE.Vector3(0, 55, 34),
  new THREE.Vector3(0, 40, 5),
  new THREE.Vector3(0, 20, 10),
  new THREE.Vector3(0, 8, 6),
  new THREE.Vector3(0, 3, 2),
  new THREE.Vector3(0, 1.6, 0),
]

// 'centripetal' (а не бывший 'catmullrom'/uniform) — контрольные точки
// выше расположены очень неравномерно (расстояния между соседними
// отличаются на порядок), а uniform-параметризация Catmull-Rom для таких
// точек штатно даёт "cusps and self-intersections" (буквальная
// формулировка из комментария в исходниках three.js) — сама библиотека
// поэтому и делает centripetal дефолтом. На сглаживание рывка взгляда
// у второй точки (см. CameraRig.tsx) это не влияет (проверено численно —
// разница в пределах погрешности), но для остальной формы пути это
// объективно корректный выбор, а не "просто дефолт".
export const cameraPath = new THREE.CatmullRomCurve3(CAMERA_PATH_POINTS, false, 'centripetal')

export const LOOK_AHEAD = 0.02

// Мировая позиция модели солнечной системы (SkyZone располагает её по
// этой же константе, см. SolarSystemModel в SkyZone.tsx) и на сколько
// прогресса растянут открывающий "взгляд туда" в начале пути — см.
// CameraRig.tsx. Камера в самой первой точке пути смотрит почти строго
// вниз (по касательной спуска), а солнечная система — широкий плоский
// диск сбоку/впереди, поэтому направление взгляда в начале сделано
// независимым от касательной пути: без этого в кадр попадал только
// центр диска (у клиента — "видно только Землю иногда и Марс").
export const SOLAR_SYSTEM_TARGET = new THREE.Vector3(0, 50, 40)
export const SOLAR_SYSTEM_SCALE = 0.33
// БЫЛО просто "1 - smoothstep(progress, 0, 0.45)" - блендинг убывал с
// САМОГО НАЧАЛА пути. Пока ближайший подлёт укладывался в одну точку
// около progress~0.22-0.24, к этому моменту блендинг ещё оставался
// достаточно высоким (~0.5+), и солнце не успевало уйти из кадра. После
// того как подлёт растянули на широкое окно 20-55% (клиент попросил
// "максимальное приближение" на весь этот диапазон, не мгновение), сама
// точка максимального сближения сдвинулась на progress~0.32 — а там
// блендинг убывающей с нуля кривой уже падал ниже 0.2, и направление
// взгляда оказывалось смесью "к солнцу" и "по касательной пути вперёд",
// причём касательная в момент пролёта указывает УЖЕ НЕ на солнце, а
// в сторону, куда камера дальше полетит - угол между реальным
// направлением на солнце и тем, куда СМОТРИТ камера, доходил до 130°+
// (проверено расчётом) — солнце физически пропадало из кадра в кульминации
// подлёта. Фикс — не "убывающий с нуля" блендинг, а "держим полностью,
// потом отпускаем": 100% до HOLD (весь approach + flyby), затем плавный
// спад к 0 до END (переход к обычному "смотреть по курсу" перед тем, как
// путь уходит в облака).
export const SOLAR_SYSTEM_LOOKAT_HOLD = 0.4
export const SOLAR_SYSTEM_LOOKAT_END = 0.55

// Финальная точка пути (0, 1.6, 0) — рост человека, задумана как "точка
// приземления в городе" (см. GroundZone.tsx), а не как продолжение
// подлёта к Земле. Но progress (store) физически НИКОГДА не достигает
// 1.0, пока 3D-сцена видна: sticky-обёртка отпускает сцену раньше
// (проверено расчётом — реальный максимум зависит от высоты вьюпорта и
// остального контента страницы, обычно ~0.85). Это значит, что кривая
// пути ВСЕГДА обрывалась намного раньше даже той точки, где начинается
// собственно нырок к поверхности — камера останавливалась в 10+ units
// над поверхностью 45-радиусной планеты, огромный шар просто "висел"
// рядом, а не проносился мимо камеры при подлёте ("приближение в землю
// максимальное", как хотел клиент).
//
// Фикс — переразметка ТОЛЬКО хвоста пути (progress >= FINAL_DESCENT_
// REMAP_START, совпадает с EarthPlanet.FADE_OUT_START / GroundZone.
// FADE_IN_START): вместо progress напрямую, для этого отрезка t
// растягивается так, чтобы реально достижимый максимум progress совпадал
// с MAX_DIVE_T, а не останавливался на месте. До порога ничего не
// меняется (непрерывный шов на самой границе) — вся уже настроенная
// тайминг-логика (туман, солнечная система, эффект ускорения) использует
// progress напрямую и этого хвоста не касается.
//
// MAX_DIVE_T = 1.0 (буквально долететь до (0,1.6,0)) — проверено
// скриншотами — оказался ПЕРЕбором: на дистанции меньше ~5 units от
// поверхности 4096x2048 текстура Земли не даёт никакой дополнительной
// детализации (не хватает разрешения) и превращается в размытое
// однотонное пятно, а сама точка (0,1.6,0) лежит внутри "танцпола"
// GroundZone на уровне глаз — камера утыкается в то место, где через
// секунду появятся здания. 0.85 — компромисс, найденный тем же способом
// (сэмплирование кривой скриптом): даёт дистанцию до поверхности ~6.4
// units — заметно ближе, чем недостижимый максимум "как было" (~10.8),
// но всё ещё в зоне, где спутниковая текстура читается чётко (горы,
// побережья, облака — проверено скриншотом).
export const FINAL_DESCENT_REMAP_START = 0.75
const MAX_DIVE_T = 0.85

export function remapPathProgress(progress: number, maxReachableProgress: number): number {
  if (progress < FINAL_DESCENT_REMAP_START || maxReachableProgress <= FINAL_DESCENT_REMAP_START) {
    return progress
  }
  const localT = (progress - FINAL_DESCENT_REMAP_START) / (maxReachableProgress - FINAL_DESCENT_REMAP_START)
  return FINAL_DESCENT_REMAP_START + THREE.MathUtils.clamp(localT, 0, 1) * (MAX_DIVE_T - FINAL_DESCENT_REMAP_START)
}
