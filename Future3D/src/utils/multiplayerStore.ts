import { create } from 'zustand'

interface MultiplayerState {
  attemptedLogin: boolean
  login: () => void
}

// Заготовка UI для входа в мультиплеер (по просьбе клиента). Настоящий
// мультиплеер (синхронизация позиций игроков, комнаты и т.п.) требует
// ОТДЕЛЬНОГО игрового сервера - сайт сейчас чисто статический (сборка +
// scp на хостинг, без бэкенда вообще). В зависимостях проекта уже есть
// colyseus.js (клиентская библиотека для игровых серверов на Colyseus) -
// она была добавлена ещё на этапе первоначальной заготовки проекта, но
// сервер, к которому подключаться, нигде не развёрнут. Форма входа
// (никнейм + кнопка "Войти") - рабочая часть, которую можно подключить к
// реальному серверу ОДНОЙ заменой login() на реальный вызов колизиуса,
// когда сервер появится - явно раскрытое ограничение, тот же принцип, что
// уже применён к оплате/разблокировке героя в этом проекте.
export const useMultiplayerStore = create<MultiplayerState>((set) => ({
  attemptedLogin: false,
  login: () => set({ attemptedLogin: true }),
}))
