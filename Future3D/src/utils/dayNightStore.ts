import { createStore } from 'zustand/vanilla'

// Полный цикл день/ночь (по просьбе клиента "сделать день/ночь") - не
// настоящее время, а игровой цикл: подобран так, чтобы смена дня и ночи
// была заметна за разумное игровое время (несколько минут исследования
// карты), а не растягивалась на часы и не мелькала слишком быстро,
// отвлекая от игры.
export const DAY_CYCLE_SECONDS = 300

interface DayNightState {
  // 0..1, 0 = полдень (см. DayNightSky.tsx: используется как фаза косинуса).
  timeOfDay: number
}

// Vanilla-стор (не React-хук) - значение мутируется КАЖДЫЙ кадр внутри
// Canvas (DayNightSky.tsx, useFrame), тот же паттерн, что у
// minimapPlayerStore.ts/craftGhostStore - обычный zustand с React-
// подпиской вызывал бы лишний ре-рендер всего дерева 60 раз в секунду
// ради одного плавно меняющегося числа, которое и не читается больше
// нигде реактивно.
export const dayNightStore = createStore<DayNightState>(() => ({
  // Старт чуть после полудня - игрок сразу видит тепло освещённую сцену
  // при входе, а не тёмную/переходную, и всё равно быстро увидит закат.
  timeOfDay: 0.08,
}))
