// Вибрация на мобильных (по просьбе клиента) - только для дискретных,
// значимых моментов (подобрал бонус, взял/сдал квест, сел/вышел из
// машины), НЕ на каждый шаг/прыжок - слишком частая вибрация ощущается
// назойливо, а не приятно. navigator.vibrate молча отсутствует на
// большинстве десктопных браузеров и на iOS Safari (Apple вообще не
// реализует этот API ни в одной версии) - вызов безопасен везде, просто
// no-op там, где не поддерживается, отдельная проверка вставлять не нужно.
export function vibrate(pattern: number | number[]) {
  if (typeof navigator === 'undefined' || typeof navigator.vibrate !== 'function') return
  try {
    navigator.vibrate(pattern)
  } catch {
    // Некоторые браузеры кидают исключение вместо тихого no-op в
    // определённых обстоятельствах (например, вкладка не в фокусе) -
    // вибрация не настолько важна, чтобы падать из-за неё.
  }
}
